modified_files = 0
for file_path in files_to_process:
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()

        original_content = content
        for old_txt, new_txt in replacements.items():
            # word boundary might be too strict for russian, so use standard replace
            content = content.replace(old_txt, new_txt)

        if content != original_content:
            with open(file_path, 'w', encoding='utf-8') as f:
                f.write(content)
            modified_files += 1
            print(f"Updated {file_path}")
    except Exception as e:
        print(f"Skipped {file_path}: {str(e)}")

print(f"Total files updated: {modified_files}")
